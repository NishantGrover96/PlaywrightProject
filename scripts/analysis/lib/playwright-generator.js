// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

async function _walkCatalog(dir, features) {
  const entries = await fs.promises.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await _walkCatalog(full, features);
    } else if (entry.name === 'feature.json') {
      try {
        const raw  = await fs.promises.readFile(full, 'utf8');
        const feat = JSON.parse(raw);
        features.push(feat);
      } catch {
        // corrupt feature.json — skip
      }
    }
  }
}

function _toDisplayName(name) {
  return name
    .replace(/[-_]+/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\b\w/g, c => c.toUpperCase());
}

function _camelCase(pascal) {
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

