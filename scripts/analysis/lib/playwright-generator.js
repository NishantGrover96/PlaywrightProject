'use strict';

/**
 * Playwright Generator — generates Playwright test artifacts for Approved features.
 *
 * Generates per feature:
 *   tests/playwright/clients/{clientId}/specs/{module}/feature-{kebab}/{kebab}.spec.ts
 *   tests/playwright/clients/{clientId}/pages/{module}/feature-{kebab}/{PascalName}Page.ts
 *   tests/playwright/clients/{clientId}/data/{module}/feature-{kebab}/test-data.json
 *   tests/playwright/clients/{clientId}/fixtures/{module}/feature-{kebab}/{kebab}.fixtures.ts
 *   tests/playwright/clients/{clientId}/specs/{module}/feature-{kebab}/README.md
 *
 * Rules:
 *   - Only generates for features with status === 'Approved'
 *   - Skips (logs reason) for all other statuses
 *   - Compares file timestamps — skips if generated file is newer than feature.json
 *   - NEVER overwrites a manually modified file (detected by checking for placeholder tokens)
 *   - Modular: can generate for one feature, one module, or entire client
 */

const fs   = require('fs');
const path = require('path');

const { toPascal } = require('./id-generator');

const ROOT = path.resolve(__dirname, '..', '..', '..');

// Token that marks a file as auto-generated and safe to overwrite
const GENERATED_MARKER = '// @generated by Repository Analysis Pipeline';

/**
 * Generate Playwright artifacts for approved features.
 *
 * @param {string}   clientId
 * @param {object[]} features     - Scored RawFeature array (read from feature.json files)
 * @param {object}   logger
 * @param {object}   [options]
 * @param {string}   [options.filterModule]   - Only generate for this module
 * @param {string}   [options.filterFeature]  - Only generate for this Feature ID
 * @returns {Promise<GenerationReport>}
 */
async function generate(clientId, features, logger, options = {}) {
  logger.section('Playwright Artifact Generation');

  const report = {
    generated: [],
    skipped:   [],
    errors:    [],
  };

  for (const feature of features) {
    // Module filter
    if (options.filterModule &&
        feature.module.toLowerCase() !== options.filterModule.toLowerCase()) {
      continue;
    }

    // Feature filter
    if (options.filterFeature && feature.featureId !== options.filterFeature) {
      continue;
    }

    // Status gate
    if (feature.status !== 'Approved') {
      const reason = `status is '${feature.status}' — must be 'Approved' to generate`;
      logger.skip(feature.featureId, reason);
      report.skipped.push({ featureId: feature.featureId, reason });
      continue;
    }

    try {
      const files = await _generateFeature(clientId, feature, logger);
      report.generated.push({ featureId: feature.featureId, files });
    } catch (err) {
      logger.error(`Generation failed for ${feature.featureId}: ${err.message}`, err);
      report.errors.push({ featureId: feature.featureId, error: err.message });
    }
  }

  logger.stat({
    'Features generated': report.generated.length,
    'Features skipped':   report.skipped.length,
    'Generation errors':  report.errors.length,
  });

  return report;
}

/**
 * Load feature objects from disk for a client, reading feature.json files.
 * Used when calling generate() standalone (not piped from detect phase).
 *
 * @param {string} clientId
 * @returns {Promise<object[]>}
 */
async function loadApprovedFeatures(clientId) {
  const catalogBase = path.join(ROOT, 'docs', 'functional-catalogs', clientId);
  if (!fs.existsSync(catalogBase)) return [];

  const features = [];
  await _walkCatalog(catalogBase, features);
  return features;
}

// ---------------------------------------------------------------------------
// Per-feature generation
// ---------------------------------------------------------------------------

async function _generateFeature(clientId, feature, logger) {
  const kebab     = feature.featureKebab;
  const moduleLc  = feature.module.toLowerCase();
  const pascal    = toPascal(kebab);
  const base      = path.join(ROOT, 'tests', 'playwright', 'clients', clientId);

  const specDir    = path.join(base, 'specs',    moduleLc, `feature-${kebab}`);
  const pagesDir   = path.join(base, 'pages',    moduleLc, `feature-${kebab}`);
  const dataDir    = path.join(base, 'data',     moduleLc, `feature-${kebab}`);
  const fixtureDir = path.join(base, 'fixtures', moduleLc, `feature-${kebab}`);

  for (const d of [specDir, pagesDir, dataDir, fixtureDir]) {
    await fs.promises.mkdir(d, { recursive: true });
  }

  const files = [];

  const writes = [
    { filePath: path.join(specDir,    `${kebab}.spec.ts`),       content: _buildSpec(feature, pascal, clientId)    },
    { filePath: path.join(pagesDir,   `${pascal}Page.ts`),       content: _buildPageObject(feature, pascal)        },
    { filePath: path.join(dataDir,    'test-data.json'),          content: _buildTestData(feature)                  },
    { filePath: path.join(fixtureDir, `${kebab}.fixtures.ts`),   content: _buildFixture(feature, pascal, clientId) },
    { filePath: path.join(specDir,    'README.md'),               content: _buildReadme(feature, clientId)          },
  ];

  for (const w of writes) {
    const written = await _safeWriteFile(w.filePath, w.content, logger);
    if (written) files.push(path.relative(ROOT, w.filePath).replace(/\\/g, '/'));
  }

  return files;
}

/**
 * Write a file if it does not exist or if it contains the generated marker.
 * Returns true if file was written, false if skipped.
 */
async function _safeWriteFile(filePath, content, logger) {
  if (fs.existsSync(filePath)) {
    // Check if it is safe to overwrite (still contains the generated marker)
    try {
      const existing = await fs.promises.readFile(filePath, 'utf8');
      if (!existing.includes(GENERATED_MARKER)) {
        logger.warn(`  [SKIP] Manually modified file preserved: ${path.basename(filePath)}`);
        return false;
      }
    } catch {
      // If we can't read it, skip to be safe
      return false;
    }
  }

  await fs.promises.writeFile(filePath, content, 'utf8');
  logger.info(`  [generated] ${path.relative(ROOT, filePath).replace(/\\/g, '/')}`);
  return true;
}

